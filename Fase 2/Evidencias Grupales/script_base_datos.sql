-- 1. Crear base de datos
CREATE DATABASE IF NOT EXISTS escuela_conductores
  CHARACTER SET utf8mb4 
  COLLATE utf8mb4_unicode_ci;

USE escuela_conductores;

-- -----------------------------------------------------
-- TABLA: ROLES
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS ROLES (
    ID_ROL INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE_ROL VARCHAR(50) NOT NULL,
    CONSTRAINT ROLES_NOMBRE_ROL_UN UNIQUE (NOMBRE_ROL)
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: SEDES
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS SEDES (
    ID_SEDE INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(100) NOT NULL,
    DIRECCION VARCHAR(255) NOT NULL,
    TELEFONO VARCHAR(20) NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: VEHICULOS
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS VEHICULOS (
    ID_VEHICULO INT AUTO_INCREMENT PRIMARY KEY,
    PATENTE VARCHAR(10) NOT NULL,
    MODELO VARCHAR(100) NOT NULL,
    TRANSMISION VARCHAR(20) NOT NULL,
    ID_SEDE INT NULL,
    ESTADO_OPERATIVO VARCHAR(30) NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT VEHICULOS_PATENTE_UN UNIQUE (PATENTE),
    CONSTRAINT FK_VEHICULO_SEDE FOREIGN KEY (ID_SEDE) 
        REFERENCES SEDES (ID_SEDE) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: USUARIOS
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS USUARIOS (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    RUT VARCHAR(12) NOT NULL,
    NOMBRE VARCHAR(100) NOT NULL,
    APELLIDO VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    ID_ROL INT NOT NULL,
    ID_SEDE INT NULL,
    ESTADO_ACTIVO TINYINT(1) DEFAULT 1,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT USUARIOS_RUT_UN UNIQUE (RUT),
    CONSTRAINT USUARIOS_EMAIL_UN UNIQUE (EMAIL),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) 
        REFERENCES ROLES (ID_ROL) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT FK_USUARIO_SEDE FOREIGN KEY (ID_SEDE) 
        REFERENCES SEDES (ID_SEDE) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: ALUMNOS_DETALLE (Relación 1:1 o 1:0..1 con USUARIOS)
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS ALUMNOS_DETALLE (
    ID_USUARIO INT PRIMARY KEY,
    ESTADO_PSICOTECNICO VARCHAR(30) NULL,
    FECHA_EVALUACION_PSICOTECNICA DATE NULL,
    OBSERVACION_PSICOTECNICA TEXT NULL,
    PORCENTAJE_ASISTENCIA_TEORICA DECIMAL(5,2) DEFAULT 0.00,
    FECHA_MATRICULA DATE NULL,
    CONSTRAINT FK_DETALLE_USUARIO FOREIGN KEY (ID_USUARIO) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: EVALUACIONES
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS EVALUACIONES (
    ID_EVALUACION INT AUTO_INCREMENT PRIMARY KEY,
    ID_ALUMNO INT NOT NULL,
    ID_INSTRUCTOR INT NOT NULL,
    TIPO_EVALUACION VARCHAR(50) NOT NULL,
    NOTA DECIMAL(4,2) NOT NULL,
    FECHA DATE NOT NULL,
    OBSERVACIONES TEXT NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_EVALUACION_ALUMNO FOREIGN KEY (ID_ALUMNO) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_EVALUACION_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: ASISTENCIAS_TEORICAS
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS ASISTENCIAS_TEORICAS (
    ID_ASISTENCIA INT AUTO_INCREMENT PRIMARY KEY,
    ID_ALUMNO INT NOT NULL,
    ID_INSTRUCTOR INT NOT NULL,
    NOMBRE_BLOQUE VARCHAR(100) NOT NULL,
    FECHA DATE NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,
    REGISTRADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_ASISTENCIA_ALUMNO FOREIGN KEY (ID_ALUMNO) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_ASISTENCIA_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: BLOQUEOS_FLOTA
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS BLOQUEOS_FLOTA (
    ID_BLOQUEO INT AUTO_INCREMENT PRIMARY KEY,
    ID_VEHICULO INT NOT NULL,
    ID_INSTRUCTOR INT NULL,
    FECHA DATE NOT NULL,
    HORA_INICIO VARCHAR(5) NOT NULL,
    HORA_FIN VARCHAR(5) NOT NULL,
    MOTIVO VARCHAR(255) NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_BLOQUEO_VEHICULO FOREIGN KEY (ID_VEHICULO) 
        REFERENCES VEHICULOS (ID_VEHICULO) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_BLOQUEO_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE SET NULL ON UPDATE CASCADE,
    INDEX IDX_BLOQUEOS_FECHA (FECHA)
) ENGINE=InnoDB;

-- -----------------------------------------------------
-- TABLA: CLASES_PRACTICAS
-- -----------------------------------------------------
CREATE TABLE IF NOT EXISTS CLASES_PRACTICAS (
    ID_CLASE INT AUTO_INCREMENT PRIMARY KEY,
    ID_ALUMNO INT NOT NULL,
    ID_INSTRUCTOR INT NOT NULL,
    ID_VEHICULO INT NOT NULL,
    ID_SEDE INT NOT NULL,
    FECHA DATE NOT NULL,
    HORA_INICIO VARCHAR(5) NOT NULL,
    HORA_FIN VARCHAR(5) NOT NULL,
    ESTADO VARCHAR(30) NOT NULL,
    TOKEN_AUTOGESTION VARCHAR(100) NULL,
    OBSERVACIONES TEXT NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CLASES_PRACTICAS_TOKEN_AUTOGESTION_UN UNIQUE (TOKEN_AUTOGESTION),
    CONSTRAINT FK_CLASE_ALUMNO FOREIGN KEY (ID_ALUMNO) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT FK_CLASE_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) 
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT FK_CLASE_VEHICULO FOREIGN KEY (ID_VEHICULO) 
        REFERENCES VEHICULOS (ID_VEHICULO) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT FK_CLASE_SEDE FOREIGN KEY (ID_SEDE) 
        REFERENCES SEDES (ID_SEDE) ON DELETE RESTRICT ON UPDATE CASCADE,
    INDEX IDX_CLASES_FECHA_SEDE (FECHA, ID_SEDE)
) ENGINE=InnoDB;