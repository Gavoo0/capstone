USE escuela_conductores;

CREATE TABLE IF NOT EXISTS preinscripciones (
    ID_PREINSCRIPCION INT AUTO_INCREMENT PRIMARY KEY,
    NOMBRE VARCHAR(150) NOT NULL,
    CONTACTO VARCHAR(150) NOT NULL,
    SEDE_PREFERIDA VARCHAR(100) NOT NULL,
    RUT VARCHAR(12) NOT NULL,
    CORREO VARCHAR(150) NOT NULL,
    TELEFONO VARCHAR(20) NOT NULL,
    ID_SEDE INT NOT NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PREINSCRIPCION_SEDE FOREIGN KEY (ID_SEDE)
        REFERENCES sedes (ID_SEDE) ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB;

