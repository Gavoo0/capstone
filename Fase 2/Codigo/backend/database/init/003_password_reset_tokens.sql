USE escuela_conductores;

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    ID_TOKEN BIGINT AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NOT NULL,
    TOKEN_HASH CHAR(64) NOT NULL,
    EXPIRA_EN DATETIME NOT NULL,
    USADO_EN DATETIME NULL,
    CREADO_EN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PASSWORD_RESET_TOKEN_HASH_UN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_PASSWORD_RESET_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES usuarios (ID_USUARIO) ON DELETE CASCADE ON UPDATE CASCADE,
    INDEX IDX_PASSWORD_RESET_USUARIO_EXPIRA (ID_USUARIO, EXPIRA_EN)
) ENGINE=InnoDB;
