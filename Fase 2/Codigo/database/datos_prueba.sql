      AND ID_VEHICULO = @vehiculo_2 AND HORA_INICIO < '16:30' AND HORA_FIN > '15:00'
  ) AND NOT EXISTS (
    SELECT 1 FROM (
      SELECT ID_BLOQUEO, FECHA, ID_VEHICULO, HORA_INICIO, HORA_FIN
      FROM BLOQUEOS_FLOTA LIMIT 18446744073709551615
